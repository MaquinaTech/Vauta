# Writes THIRD_PARTY_LICENSES.txt: every licence file found under the resolved package checkouts (the pinned mlx-swift fork and
# what it vendors, and swift-numerics), each with its path and full text. Run it after any change of Package.resolved and commit
# the result; NOTICE refers to it. It enumerates the checkouts instead of guessing the list.
#
#   scripts/list-third-party-licences.sh            write THIRD_PARTY_LICENSES.txt
#   scripts/list-third-party-licences.sh --check    fail if the file is out of date
set -euo pipefail
cd "$(dirname "$0")/.."
CHECKOUTS=".build/checkouts"
[[ -d "$CHECKOUTS" ]] || { echo "ERROR: run swift build first (no $CHECKOUTS)." >&2; exit 1; }

OUT="$(mktemp)"
{
  echo "Third-party licences compiled into Vauta"
  echo "========================================"
  echo
  echo "Generated by scripts/list-third-party-licences.sh from the resolved packages in Package.resolved."
  echo "Do not edit by hand."
  while IFS= read -r file; do
    echo
    echo "--------------------------------------------------------------------------------"
    echo "${file#"$CHECKOUTS"/}"
    echo "--------------------------------------------------------------------------------"
    echo
    cat "$file"
  done < <(find "$CHECKOUTS" -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) -not -path '*/.git/*' | LC_ALL=C sort)
  # Code that Vauta ports in part but does not link (mlx-lm, MIT): its licence is kept here too.
  echo
  echo "--------------------------------------------------------------------------------"
  echo "mlx-lm/LICENSE (portions of Sources/VautaMLX/LLM are derived from mlx-lm 0.32.0)"
  echo "--------------------------------------------------------------------------------"
  echo
  cat docs/third-party/mlx-lm-LICENSE
} > "$OUT"

if [[ "${1:-}" == "--check" ]]; then
  cmp -s "$OUT" THIRD_PARTY_LICENSES.txt || { rm -f "$OUT"; echo "ERROR: THIRD_PARTY_LICENSES.txt is out of date." >&2; exit 1; }
  rm -f "$OUT"
  echo "THIRD_PARTY_LICENSES.txt is up to date."
else
  mv "$OUT" THIRD_PARTY_LICENSES.txt
  echo "Wrote THIRD_PARTY_LICENSES.txt ($(grep -c '^-----' THIRD_PARTY_LICENSES.txt | awk '{print $1/2}') licence files)."
fi
