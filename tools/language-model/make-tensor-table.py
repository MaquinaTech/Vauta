"""Writes the generated Swift sources of Sources/VautaCore/LanguageModel/ from the manifest of make-manifest.py.

usage: make-tensor-table.py <manifest.json> <out-dir>

Writes LanguageModelManifest.swift (constants) and LanguageModelTable*.swift (the 719 source tensors, the 225 block hashes and
the 1,355 output tensors as text tables, split so that no file passes about 600 lines). A test compares them with
Tests/VautaCoreTests/Fixtures/LanguageModel/manifest.json.
"""
import json, os, sys

m = json.load(open(sys.argv[1]))
out = sys.argv[2]
HEAD = '''// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 Nicolás López de Lerma López

// Generated by tools/language-model/make-tensor-table.py. Do not edit.

'''
src = ["|".join([t["name"], ",".join(map(str, t["shape"])), str(t["offset"]), str(t["size"]), t["sha256"], t["action"]]) for t in m["tensors"]]
outs = ["|".join([t["name"], t["dtype"], ",".join(map(str, t["shape"])), str(t["offset"]), str(t["size"]), t["sha256"]]) for t in m["outputs"]]
blocks = m["blocks"]
PART = 560


def table(name, doc, lines):
    return f'''    /// {doc}
    static let {name} = """
{chr(10).join(lines)}
"""
'''


def write(fn, body):
    open(os.path.join(out, fn), "w").write(HEAD + "extension LanguageModelTable {\n" + body + "}\n")


s1, s2 = src[:PART], src[PART:]
write("LanguageModelTableSource1.swift", table("sourcePart1", "Source tensors, first part: name|shape|offset in the span|size|sha256|action.", s1))
write("LanguageModelTableSource2.swift", table("sourcePart2", "Source tensors, second part.", s2) + "\n" +
      table("blockTable", f'SHA-256 of each {m["blockSize"]}-byte block of the span, in order.', blocks))
for i in range(0, len(outs), PART):
    n = i // PART + 1
    write(f"LanguageModelTableOutput{n}.swift", table(f"outputPart{n}", "Output tensors: name|dtype|shape|offset in the data|size|sha256.", outs[i:i + PART]))
nparts = (len(outs) + PART - 1) // PART
tok = m["small"]["tokenizer.json"]
open(os.path.join(out, "LanguageModelManifest.swift"), "w").write(HEAD + f'''import Foundation

/// Everything that identifies the one integrated language model: Google's `google/gemma-4-E4B-it` at a pinned revision, the
/// language tower only, quantised on this Mac to 4-bit affine (group 64). Derived once from the verified original file by
/// tools/language-model/make-manifest.py (docs/LANGUAGE_MODEL.md) and pinned in source.
public enum LanguageModelManifest {{
    public static let repository = "{m["repository"]}"
    public static let revision = "{m["revision"]}"
    public static let revisionFolder = "{m["revision"][:8]}"

    public static let sourceFile = "{m["sourceFile"]}"
    public static let sourceSize = {m["sourceSize"]}
    public static let sourceSHA256 = "{m["sourceSHA256"]}"
    public static let sourceHeaderSize = {m["sourceHeaderSize"]}
    public static let sourceHeaderSHA256 = "{m["sourceHeaderSHA256"]}"
    /// The language tower: the {len(m["tensors"])} `model.language_model.*` tensors are one contiguous byte range of the original file.
    public static let spanStart = {m["spanStart"]}
    public static let spanEnd = {m["spanEnd"]}
    public static var spanSize: Int {{ spanEnd - spanStart }}
    public static let blockSize = {m["blockSize"]}
    /// Layers from this one on reuse the keys and values of an earlier layer and carry no k/v projections of their own.
    public static let firstSharedLayer = {m["firstSharedLayer"]}

    public static let assembledFile = "model.safetensors"
    public static let assembledHeaderSize = {m["outputHeaderSize"]}
    public static let assembledHeaderSHA256 = "{m["outputHeaderSHA256"]}"
    public static let assembledSize = {m["assembledSize"]}
    public static let assembledSHA256 = "{m["assembledSHA256"]}"

    public static let tokenizerFile = "tokenizer.json"
    public static let tokenizerSize = {tok["size"]}
    public static let tokenizerSHA256 = "{tok["sha256"]}"

    static let outputParts = {nparts}
}}

/// The generated tables (see the `LanguageModelTable*.swift` files).
enum LanguageModelTable {{}}
''')
print("wrote", len(src), "source,", len(outs), "outputs,", len(blocks), "blocks")
