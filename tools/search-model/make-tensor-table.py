"""Writes Sources/VautaCore/SearchModel/SearchModelTable.swift from a manifest JSON (see docs/SEARCH_MODEL.md).

usage: make-tensor-table.py <text_manifest.json> <out.swift>

The manifest is derived once from the verified original model.safetensors (a different, developer-side step that is never run
against user data). The generated file is committed; a test compares it with Tests/VautaCoreTests/Fixtures/SearchModel/text_manifest.json.
"""
import json, sys

m = json.load(open(sys.argv[1]))
lines = []
for t in m["tensors"]:
    lines.append("|".join([t["name"], t["dtype"], ",".join(map(str, t["shape"])), str(t["offset"]), str(t["size"]), t["sha256"]]))
blocks = "\n".join(m["blocks"])
out = f'''// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 Nicolás López de Lerma López

// Generated by tools/search-model/make-tensor-table.py. Do not edit.

extension SearchModelManifest {{
    /// One line per tensor of the text tower: name|dtype|shape|offset in the span|size|sha256.
    static let tensorTable = """
{chr(10).join(lines)}
"""

    /// SHA-256 of each {m["block_size"]}-byte block of the span, in order.
    static let blockTable = """
{blocks}
"""
}}
'''
open(sys.argv[2], "w").write(out)
