import Foundation

/// Golden sentences for the question cues. `asked` are information questions with their question mark (a candidate at Standard),
/// `unpunctuated` are questions the transcriber left without a mark (a candidate at More answers), `statements` are not questions,
/// and `chatter` are tags, audio checks and greetings that carry a question mark but are never candidates at Standard.
struct CueGolden {
    let locale: String
    let asked: [String]
    let unpunctuated: [String]
    let statements: [String]
    let chatter: [String]
    /// Opinions and proposals: still candidates (the model check decides), listed so the penalty is tested.
    let opinions: [String]
}

